def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def fbm(shape, scale_px, seed, octaves=3):
    """Smooth value noise ~N(0,1)-ish at a given feature size (px)."""
    rng = np.random.default_rng(seed)
    h, w = shape
    out = np.zeros(shape, np.float32); amp = 1.0; tot = 0
    for o in range(octaves):
        s = max(1.0, scale_px / (2 ** o))
        n = rng.standard_normal((int(h / s) + 3, int(w / s) + 3)).astype(np.float32)
        n = cv2.resize(n, (int((w / s + 3) * s), int((h / s + 3) * s)), interpolation=cv2.INTER_CUBIC)[:h, :w]
        out += n * amp; tot += amp; amp *= 0.5
    return out / tot * 1.6


# ------------------------------------------------------------------ ecology rasters
def flow_accumulation(T):
    """D8 flow accumulation (cells), processed high -> low."""
    Tp = np.pad(T, 1, mode='edge')
    best = np.zeros_like(T); recv = np.arange(H * W).reshape(H, W)
    ids = np.arange(H * W).reshape(H, W)
    idsp = np.pad(ids, 1, mode='edge')
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            if dx == 0 and dy == 0:
                continue
            nb = Tp[1 + dy:1 + dy + H, 1 + dx:1 + dx + W]
            drop = (T - nb) / math.hypot(dx, dy)
            m = drop > best
            best[m] = drop[m]
            recv[m] = idsp[1 + dy:1 + dy + H, 1 + dx:1 + dx + W][m]
    order = np.argsort(-T.ravel(), kind='stable')
    acc = np.ones(H * W, np.float64)
    r = recv.ravel()
    for i in order.tolist():
        j = r[i]
        if j != i:
            acc[j] += acc[i]
    return acc.reshape(H, W)


def corridor_edge_distance(features, hw_fn, scale=2):
    """Distance (m) from each 2x-res cell to the nearest corridor EDGE (negative on the corridor),
    plus the (tree, brush) clear zone of that nearest corridor. Returns full-res-2x arrays."""
    Hs, Ws = H * scale, W * scale
    hw = np.zeros((Hs, Ws), np.float32); ct = np.zeros((Hs, Ws), np.float32); cb = np.zeros((Hs, Ws), np.float32)
    lines = []
    for f in features:
        r = hw_fn(f)
        if r is None:
            continue
        lines.append((r[0], r[1], r[2], np.asarray(f['geometry']['coordinates'])[:, :2]))
    lines.sort(key=lambda t: t[0])  # wide roads drawn last (win at junctions)
    cen = np.zeros((Hs, Ws), np.uint8)
    for w, ctree, cbrush, c in lines:
        pts = (c * scale).round().astype(np.int32)
        cv2.polylines(cen, [pts], False, 1, 1)
        cv2.polylines(hw, [pts], False, float(w), 1)
        cv2.polylines(ct, [pts], False, float(ctree), 1)
        cv2.polylines(cb, [pts], False, float(cbrush), 1)
    if not cen.any():
        big = np.full((Hs, Ws), 1e4, np.float32)
        return big, np.zeros_like(big), np.zeros_like(big)
    d, (iy, ix) = ndi.distance_transform_edt(cen == 0, return_indices=True)
    d = d * MPP / scale
    return (d - hw[iy, ix]).astype(np.float32), ct[iy, ix], cb[iy, ix]


def ecology(T, cls):
    gy, gx = np.gradient(cv2.GaussianBlur(T, (0, 0), 1.0), MPP)
    slope = np.hypot(gx, gy)
    # aspect: sun exposure (south / south-west faces are dry and warm in the southern Appalachians)
    # image y grows south: downslope direction = (-gx, -gy); facing south => -gy > 0
    nrm = np.maximum(slope, 1e-6)
    south = (-gy / nrm) * 0.8 + (gx / nrm) * 0.35 * -1  # west component (x grows east)
    sun = np.clip(south * np.clip(slope * 3, 0, 1), -1, 1)
    tpi_s = T - cv2.GaussianBlur(T, (0, 0), 8)     # ~20 m: gullies / spurs
    tpi_l = T - cv2.GaussianBlur(T, (0, 0), 40)    # ~100 m: ridges / coves
    tpi = np.clip(tpi_l / 25 + tpi_s / 6, -1.5, 1.5)
    acc = flow_accumulation(T)
    wet = cls == WATER
    dwater = ndi.distance_transform_edt(~wet) * MPP
    moist = (np.clip((np.log(acc) - 1.5) / 6, 0, 1) * 0.45 + np.clip(-tpi, 0, 1) * 0.35 + np.exp(-dwater / 35) * 0.45
             - np.clip(sun, 0, 1) * 0.2 - np.clip(tpi, 0, 1) * 0.2 + 0.15)
    moist = cv2.GaussianBlur(np.clip(moist, 0, 1).astype(np.float32), (0, 0), 1.2)
    return dict(slope=slope, sun=sun, tpi=tpi, moist=moist, dwater=dwater, acc=acc)


# ------------------------------------------------------------------ fields
def fields(cls, rng, noise):
    """Partition open rural land into fields: returns field-type raster, angle raster, hedge mask."""
    openr = np.isin(cls, [FARM, MEADOW])
    lab, n = ndi.label(openr)
    ftype = np.zeros((H, W), np.uint8); fang = np.zeros((H, W), np.float32)
    # Voronoi subdivision (~120-200 m fields), boundaries wobble a little with noise
    seeds = []
    ys, xs = np.nonzero(openr)
    if len(xs):
        nseed = max(1, int(openr.sum() * MPP * MPP / 26000))
        pick = rng.choice(len(xs), nseed, replace=False)
        seeds = np.stack([xs[pick], ys[pick]], 1).astype(np.float32)
        gy_, gx_ = np.mgrid[0:H, 0:W].astype(np.float32)
        wob = noise * 4
        best = np.full((H, W), 1e9, np.float32); cell = np.zeros((H, W), np.int32)
        for k, (sx, sy) in enumerate(seeds):
            x0, x1 = int(max(0, sx - 110)), int(min(W, sx + 110)); y0, y1 = int(max(0, sy - 110)), int(min(H, sy + 110))
            d = np.hypot(gx_[y0:y1, x0:x1] - sx + wob[y0:y1, x0:x1], gy_[y0:y1, x0:x1] - sy - wob[y0:y1, x0:x1])
            m = d < best[y0:y1, x0:x1]
            best[y0:y1, x0:x1][m] = d[m]; cell[y0:y1, x0:x1][m] = k + 1
        cell[~openr] = 0
        # an isolated small clearing is a single field
        cid = cell + lab * 10000
        types = []
        for k in range(len(seeds)):
            types.append(k)
        uid, inv = np.unique(cid[openr], return_inverse=True)
        r = np.random.default_rng(11)
        tsel = r.random(len(uid)); ang = r.uniform(0, math.pi, len(uid))
        # majority class of each field decides the menu
        is_farm = ndi.mean((cls[openr] == FARM).astype(np.float32), labels=inv, index=np.arange(len(uid))) > 0.5
        t_farm = np.select([tsel < 0.42, tsel < 0.72, tsel < 0.84], [FIELD_TYPES['pasture'], FIELD_TYPES['hay'], FIELD_TYPES['plowed']], FIELD_TYPES['fallow'])
        t_mead = np.select([tsel < 0.45], [FIELD_TYPES['pasture']], FIELD_TYPES['fallow'])
        tt = np.where(is_farm, t_farm, t_mead).astype(np.uint8)
        ftype[openr] = tt[inv]; fang[openr] = ang[inv]
        # hedgerows: field-to-field boundaries + open-land boundary (fence lines)
        er = cv2.erode(cid.astype(np.float32), np.ones((3, 3), np.uint8)); dl = cv2.dilate(cid.astype(np.float32), np.ones((3, 3), np.uint8))
        hedge = ((er != dl) & openr)
    else:
        hedge = np.zeros((H, W), bool)
    lawn = np.isin(cls, [RES, TOWN, COM])
    ftype[lawn & (ftype == 0)] = FIELD_TYPES['lawn']
    return ftype, fang, hedge


# ------------------------------------------------------------------ scatter
def _jitter_grid(cell_px, rng, prob):
    gx, gy = np.meshgrid(np.arange(0, W, cell_px), np.arange(0, H, cell_px))
    x = (gx + rng.random(gx.shape) * cell_px).ravel(); y = (gy + rng.random(gy.shape) * cell_px).ravel()
    xi, yi = np.clip(x.astype(int), 0, W - 1), np.clip(y.astype(int), 0, H - 1)
    keep = rng.random(len(x)) < prob[yi, xi]
    return x[keep], y[keep], xi[keep], yi[keep]


def _choose(rng, weights, n=None):
    """weights: dict name -> array(n). Returns species ids."""
    names = list(weights)
    n = n if n is not None else max(np.size(v) for v in weights.values())
    Wm = np.stack([np.broadcast_to(np.maximum(np.asarray(weights[k], np.float64), 0), (n,)) for k in names], 1) + 1e-9
    c = np.cumsum(Wm, 1); c /= c[:, -1:]
    u = rng.random((len(c), 1))
    k = (u > c).sum(1)
    return np.array([SID[names[i]] for i in k], np.int32)


def scatter(T, cls, seed=7):
    rng = np.random.default_rng(seed)
    eco = ecology(T, cls)
    slope, sun, tpi, moist, dwater = eco['slope'], eco['sun'], eco['tpi'], eco['moist'], eco['dwater']
    cr = np.asarray(Image.open(path('data/landuse/conifer_ratio.png')), np.float32) / 255
    wet = cls == WATER
    forest = np.isin(cls, [HARD, CONI])
    rock = cls == ROCK
    # A1: real rock exposure (crags, cut banks, rapids banks) + bank/bed type along channels
    rp = path('data/terrain/rock_exposure_u8.png')
    rexp = cv2.GaussianBlur(np.asarray(Image.open(rp), np.float32) / 255, (0, 0), 0.8) if os.path.exists(rp) else rock.astype(np.float32)
    fxp = path('data/terrain/water_fx_u8.bin')
    btype = np.zeros((H, W), np.float32)
    if os.path.exists(fxp):
        raw = np.fromfile(fxp, np.uint8)
        btype = raw.reshape(raw.size // (H * W), H, W)[3].astype(np.float32) / 255 * 2 - 1   # -1 gravel bar .. +1 rock
    gravelbar = cv2.dilate(np.clip(-btype - 0.2, 0, 1), np.ones((3, 3), np.uint8))
    rock = rock | (rexp > 0.5)
    n40 = fbm((H, W), 16, seed + 1)      # 40 m edge wobble
    n15 = fbm((H, W), 6, seed + 2)       # 15 m
    n100 = fbm((H, W), 40, seed + 3)     # 100 m stand patches
    # signed distance to the forest boundary (m), displaced by noise -> irregular edges
    sd = (ndi.distance_transform_edt(forest) - ndi.distance_transform_edt(~forest)) * MPP
    sdn = sd + n40 * 9 + n15 * 4
    drock = ndi.distance_transform_edt(~rock) * MPP
    # corridors (2x res)
    rt = load_json(path('data/roads/road_types.json'))['types']
    def road_hw(f):
        p = f['properties']
        if p.get('virtual'):
            return None
        c = CLEAR.get(p['type'], (3, 1))
        return (p.get('width_m') or rt[p['type']]['width_m']) / 2 + (p.get('shoulder_m') or 0), c[0], c[1]
    road_d, road_ct, road_cb = corridor_edge_distance(load_json(path('data/roads/roads.geojson'))['features'], road_hw)
    rail_d, _, _ = corridor_edge_distance(load_json(path('data/railways/railways.geojson'))['features'], lambda f: (f['properties']['width_m'] / 2, 6, 3))
    # bridges: keep the deck corridor (and a margin) free, also where the road crosses dry ground
    rds = {f['properties']['id']: f for f in load_json(path('data/roads/roads.geojson'))['features']}
    def bridge_hw(f):
        return (f['properties'].get('deck_width_m') or 10) / 2, 0, 0
    br_feats = [f for f in load_json(path('data/roads/bridges.geojson'))['features'] if f['geometry']['coordinates']]
    bridge_d, _, _ = corridor_edge_distance(br_feats, bridge_hw)
    def min2(a):  # conservative 2x -> 1x (min distance in each 2x2 block)
        return a.reshape(H, 2, W, 2).min(axis=(1, 3))
    road1 = min2(road_d); rail1 = min2(rail_d); bridge1 = min2(bridge_d)
    ftype, fang, hedge = fields(cls, rng, n15)

    def sample2(a, x, y):
        return a[np.clip((y * 2).astype(int), 0, H * 2 - 1), np.clip((x * 2).astype(int), 0, W * 2 - 1)]

    def clear_ok(x, y, layer):
        """layer 0 = tree trunk, 1 = brush/shrub."""
        rd = sample2(road_d, x, y); ct = sample2(road_ct, x, y); cb = sample2(road_cb, x, y)
        ra = sample2(rail_d, x, y); bd = sample2(bridge_d, x, y)
        xi, yi = np.clip(x.astype(int), 0, W - 1), np.clip(y.astype(int), 0, H - 1)
        dw = dwater[yi, xi]
        if layer == 0:
            return (rd > ct + rng.random(len(x)) * 3) & (ra > 7 + rng.random(len(x)) * 3) & (bd > BRIDGE_CLEAR + 2) & (dw > 3.0) & ~wet[yi, xi]
        return (rd > cb + rng.random(len(x)) * 1.0) & (ra > 4.5) & (bd > BRIDGE_CLEAR) & (dw > 1.0) & ~wet[yi, xi]

    dev = np.isin(cls, [RES, TOWN])
    pts = []  # (x, y, species, scale)

    # ---- 1) canopy trees
    edge_in = smoothstep(-2, 10, sdn)
    n8 = fbm((H, W), 3.5, seed + 4)
    gaps = np.clip(0.8 + 0.3 * n100 + 0.15 * n15 + 0.12 * n8, 0.3, 1.0)  # small canopy gaps + clumps
    p_can = np.zeros((H, W), np.float32)
    p_can += forest * 0.95 * edge_in * gaps
    p_can = np.maximum(p_can, (sdn > -4) * edge_in * 0.9 * gaps * ~np.isin(cls, [FARM, COM, IND, RAIL]))  # forest tongues
    p_can[rock] = 0.62 * np.clip(0.6 + 0.4 * n15[rock], 0, 1) * np.where(slope[rock] > 0.9, 0.5, 1.0)
    p_can *= 1 - 0.8 * np.clip(rexp, 0, 1)   # bare crags / cut banks
    p_can *= 1 - np.clip(gravelbar, 0, 1)    # open gravel bars
    p_can = np.where(dev, np.clip(0.2 + 0.18 * n100, 0.03, 0.45), p_can)
    p_can[cls == COM] = 0.05; p_can[cls == IND] = 0.03; p_can[cls == RAIL] = 0.0
    p_can[cls == MEADOW] = np.maximum(p_can[cls == MEADOW] * 0.4, 0.008)
    p_can[cls == FARM] = 0.0
    p_can *= np.where(slope > 1.1, 0.6, 1.0)
    x, y, xi, yi = _jitter_grid(1.75, rng, p_can)
    ok = clear_ok(x, y, 0); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
    m = moist[yi, xi]; r = np.clip(tpi[yi, xi], -1, 1); s = sun[yi, xi]; c = cr[yi, xi]
    dry = np.clip(0.5 * np.clip(s, 0, 1) + 0.5 * np.clip(r, 0, 1) + 0.4 * (0.5 - m), 0, 1)
    ridge = np.clip(r, 0, 1); cove = np.clip(-r, 0, 1)
    creek = np.exp(-dwater[yi, xi] / 30)
    rk = np.exp(-drock[yi, xi] / 25)
    edge = np.exp(-np.abs(sdn[yi, xi]) / 12) * forest[yi, xi]
    d = dev[yi, xi]
    w = {
        'WhiteOak_A': (0.5 + 1.2 * dry + 0.5 * ridge) * (1 - 0.5 * cove) * (1 - d * 0.5),
        'WhiteOak_B': (0.5 + 1.0 * dry + 0.4 * ridge) * (1 - 0.5 * cove),
        'Hickory_A': 0.25 + 0.6 * dry,
        'RedMaple_A': 0.45 + 0.5 * m + 0.6 * edge + 0.4 * d,
        'RedMaple_B': 0.3 + 0.4 * m + 0.8 * edge + 0.5 * d,
        'TulipPoplar_A': (0.12 + 1.6 * m * (1 - ridge)) * (1 - 0.6 * dry),
        'TulipPoplar_B': (0.1 + 1.2 * m * (1 - ridge)) * (1 - 0.5 * dry),
        'Hemlock_A': (0.04 + 2.2 * creek + 0.9 * cove * m) * (0.4 + 1.2 * c) * (1 - d * 0.8),
        'Hemlock_B': (0.03 + 1.6 * creek + 0.6 * cove * m) * (0.4 + 1.2 * c) * (1 - d * 0.8),
        'WhitePine_A': (0.08 + 0.7 * ridge + 0.3 * edge) * (0.3 + 1.8 * c) + 0.15 * d,
        'WhitePine_B': (0.06 + 0.5 * ridge + 0.4 * edge) * (0.3 + 1.6 * c) + 0.1 * d,
        'VirginiaPine': (0.02 + 1.2 * rk + 0.5 * dry * ridge) * (0.5 + c),
        'Oak_OpenGrown': 0.02 + 0.5 * edge * (1 - forest[yi, xi] * 0.5) + 0.5 * d,
        'Dogwood': 0.25 * d,
        'Snag_A': 0.012 + 0.05 * rk + 0.012 * ridge,
        'Snag_B': 0.008 + 0.03 * rk,
    }
    # stands: each species clumps in ~50-80 m patches (not salt-and-pepper mixing)
    for k_, name in enumerate(w):
        fld = fbm((H, W), 22 + 3 * (k_ % 4), 100 + k_, 2)
        w[name] = np.asarray(w[name]) * np.exp(0.8 * fld[yi, xi])
    sp = _choose(rng, w)
    sc = np.exp(rng.normal(0, 0.14, len(x))) * (1 + 0.12 * cove - 0.12 * ridge - 0.25 * rk * (1 - cove)) * np.where(d, 0.9, 1.0)
    sc *= np.where(slope[yi, xi] > 0.8, 0.9, 1.0)
    pts.append((x, y, sp, sc))

    # ---- 2) understory (inside forest): dogwood, saplings, rhododendron/laurel thickets
    p_und = forest * edge_in * (0.18 + 0.25 * np.clip(moist, 0, 1)) + forest * 0.1 * np.clip(-tpi, 0, 1)
    x, y, xi, yi = _jitter_grid(2.2, rng, p_und.astype(np.float32))
    ok = clear_ok(x, y, 1); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
    m = moist[yi, xi]; r = np.clip(tpi[yi, xi], -1, 1); creek = np.exp(-dwater[yi, xi] / 25); rk = np.exp(-drock[yi, xi] / 30)
    thicket = np.clip(n15[yi, xi] * 0.7 + 0.3, 0, 1)
    w = {
        'Rhododendron_A': (0.1 + 2.0 * creek + 1.2 * np.clip(-r, 0, 1) * m) * (0.4 + thicket),
        'Laurel_B': (0.1 + 0.9 * np.clip(r, 0, 1) + 0.8 * rk) * (0.4 + thicket),
        'Dogwood': 0.45 * (1 - m * 0.5),
        'Sapling_HW_A': 0.5, 'Sapling_HW_B': 0.4,
        'Sapling_Pine': 0.15 + 0.3 * cr[yi, xi],
        'Brush_B': 0.15,
    }
    sp = _choose(rng, w)
    pts.append((x, y, sp, np.exp(rng.normal(0, 0.18, len(x))) * 0.95))

    # ---- 3) edge transition belt (open side of forest edges): brush, saplings, young pines
    belt = np.exp(-((sdn + 7) / 8) ** 2) * ~forest * ~wet * ~np.isin(cls, [COM, IND, RAIL]) * (1 - 0.6 * dev)
    belt = np.maximum(belt, np.exp(-((sdn - 1) / 4) ** 2) * forest * 0.7)
    x, y, xi, yi = _jitter_grid(1.3, rng, (belt * 0.55).astype(np.float32))
    ok = clear_ok(x, y, 1); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
    w = {'Brush_A': 1.0, 'Brush_B': 0.9, 'Sapling_HW_A': 0.5, 'Sapling_HW_B': 0.35, 'Sapling_Pine': 0.35 + 0.4 * cr[yi, xi],
         'VirginiaPine': 0.12, 'RedMaple_B': 0.12, 'Dogwood': 0.12}
    sp = _choose(rng, w)
    pts.append((x, y, sp, np.exp(rng.normal(-0.05, 0.2, len(x)))))

    # ---- 4) hedgerows / fence lines between fields (gappy), with fence-line trees
    hd = cv2.dilate(hedge.astype(np.uint8), np.ones((2, 2), np.uint8)) > 0
    hp = hd * np.clip(0.55 + 0.45 * n40, 0, 1) * (n15 > -0.6)
    x, y, xi, yi = _jitter_grid(1.2, rng, (hp * 0.6).astype(np.float32))
    ok = clear_ok(x, y, 1); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
    w = {'Brush_A': 1.2, 'Brush_B': 1.0, 'Sapling_HW_A': 0.4, 'RedMaple_B': 0.25, 'Oak_OpenGrown': 0.12, 'WhiteOak_B': 0.12,
         'Sapling_Pine': 0.2, 'VirginiaPine': 0.12, 'Hickory_A': 0.06, 'Dogwood': 0.1}
    sp = _choose(rng, w, len(x))
    tree = ~np.isin(sp, [SID['Brush_A'], SID['Brush_B'], SID['Sapling_HW_A'], SID['Sapling_Pine']])
    ok = clear_ok(x, y, 0) | ~tree
    pts.append((x[ok], y[ok], sp[ok], np.exp(rng.normal(-0.05, 0.18, ok.sum()))))

    # ---- 5) lone open-grown trees in pastures / meadows + yard trees
    lone = np.isin(ftype, [FIELD_TYPES['pasture'], FIELD_TYPES['fallow']]) * 0.0035 + (cls == MEADOW) * 0.006
    x, y, xi, yi = _jitter_grid(2.0, rng, lone.astype(np.float32))
    ok = clear_ok(x, y, 0); x, y = x[ok], y[ok]
    sp = _choose(rng, {'Oak_OpenGrown': np.full(len(x), 1.0), 'RedMaple_A': np.full(len(x), 0.25), 'WhitePine_A': np.full(len(x), 0.15), 'Hickory_A': np.full(len(x), 0.1)})
    pts.append((x, y, sp, np.exp(rng.normal(0.05, 0.15, len(x)))))

    # ---- 6) roadside / railside brush & weeds (outside the mowed clear zone, open land)
    rs = (np.exp(-np.clip(road1 - 3, 0, None) / 4) * (road1 > 1) + np.exp(-np.clip(rail1 - 3, 0, None) / 4) * (rail1 > 2)) \
        * ~wet * np.isin(cls, [MEADOW, FARM, HARD, CONI, ROCK, RES]) * np.clip(0.4 + 0.6 * n15, 0, 1)
    x, y, xi, yi = _jitter_grid(1.4, rng, (rs * 0.35).astype(np.float32))
    ok = clear_ok(x, y, 1); x, y = x[ok], y[ok]
    sp = _choose(rng, {'Brush_A': np.full(len(x), 1.0), 'Brush_B': np.full(len(x), 1.3), 'Sapling_HW_A': np.full(len(x), 0.25), 'Sapling_Pine': np.full(len(x), 0.15)})
    pts.append((x, y, sp, np.exp(rng.normal(-0.1, 0.2, len(x)))))

    # ---- 7) creek-bank thickets (dense near water, outside the channel)
    bank = np.exp(-((dwater - 5) / 5) ** 2) * ~wet * ~np.isin(cls, [COM, IND, RAIL, FARM]) * (1 - 0.7 * dev) * (1 - np.clip(gravelbar, 0, 1)) * (1 - 0.7 * np.clip(rexp, 0, 1))
    x, y, xi, yi = _jitter_grid(1.4, rng, (bank * 0.4).astype(np.float32))
    ok = clear_ok(x, y, 1); x, y = x[ok], y[ok]
    sp = _choose(rng, {'Rhododendron_A': np.full(len(x), 1.0), 'Laurel_B': np.full(len(x), 0.5), 'Brush_A': np.full(len(x), 0.8),
                       'RedMaple_B': np.full(len(x), 0.25), 'Sapling_HW_B': np.full(len(x), 0.3), 'Hemlock_B': np.full(len(x), 0.2)})
    pts.append((x, y, sp, np.exp(rng.normal(0, 0.18, len(x)))))

    X = np.concatenate([p[0] for p in pts]); Y = np.concatenate([p[1] for p in pts])
    S = np.concatenate([p[2] for p in pts]).astype(np.int32); SC = np.concatenate([p[3] for p in pts]).astype(np.float32)
    for a, b, frac in VARIANTS:  # spread the most common species over more meshes (less visible repetition)
        sel = (S == SID[a]) & (rng.random(len(S)) < frac)
        S[sel] = SID[b]
    xi, yi = np.clip(X.astype(int), 0, W - 1), np.clip(Y.astype(int), 0, H - 1)
    Z = T[yi, xi]
    veg = np.stack([X, Y, Z, SC, S.astype(np.float32), rng.random(len(X))], 1).astype(np.float32)

    # ---- canopy cover raster from the actual trees (terrain: forest floor under trees)
    big = ~np.isin(S, [SID[n] for n in NOT_WEB | {'Sapling_HW_A', 'Sapling_Pine', 'Dogwood'}])
    cov = np.zeros((H, W), np.float32)
    np.add.at(cov, (yi[big], xi[big]), 1.0)
    cov = np.clip(cv2.GaussianBlur(cov, (0, 0), 2.2) * 9, 0, 1)

    props = scatter_props(rng, T, cls, eco, forest, sdn, rock, drock, road1, rail1, wet, n15, clear_ok)
    # ---- eco raster
    disturbed = np.clip(np.exp(-np.clip(road1, 0, None) / 6) * 0.8 + np.exp(-np.clip(rail1, 0, None) / 8) + np.isin(cls, [IND, RAIL]) * 0.8
                        + (cls == COM) * 0.35, 0, 1)
    talus = np.clip(np.exp(-drock / 18) * smoothstep(0.25, 0.6, slope) + (cls == ROCK) * 0.5 + gravelbar * 0.8, 0, 1)
    eco_u8 = np.stack([
        moist, disturbed, cov, ftype.astype(np.float32) / 255, fang / math.pi, hedge.astype(np.float32),
        np.clip(tpi / 3 + 0.5, 0, 1), talus,
        # corridor edge distances (m / 25.5, 0.1 m steps): ground cover keeps pavement, ballast and bridge decks clear
        np.clip(road1, 0, 25.5) / 25.5, np.clip(np.minimum(rail1, bridge1), 0, 25.5) / 25.5, np.clip(rexp, 0, 1)], -1)
    eco_u8 = (np.clip(eco_u8, 0, 1) * 255).round().astype(np.uint8)
    eco_u8[..., 3] = ftype
    return veg, props, eco_u8


def scatter_props(rng, T, cls, eco, forest, sdn, rock, drock, road1, rail1, wet, n15, clear_ok):
    slope, dwater, moist, tpi = eco['slope'], eco['dwater'], eco['moist'], eco['tpi']
    out = []
    def add(prob, cell, kinds, scale_mu, scale_sd, layer=0, allow_water=False):
        x, y, xi, yi = _jitter_grid(cell, rng, np.clip(prob, 0, 1).astype(np.float32))
        if not allow_water:
            ok = clear_ok(x, y, layer); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
        else:
            ok = (road1[yi, xi] > 2) & (rail1[yi, xi] > 2); x, y, xi, yi = x[ok], y[ok], xi[ok], yi[ok]
        names = list(kinds); p = np.array([kinds[n] for n in names], float); p /= p.sum()
        k = rng.choice(len(names), len(x), p=p)
        kid = np.array([PID[names[i]] for i in k])
        out.append(np.stack([x, y, T[yi, xi], np.exp(rng.normal(scale_mu, scale_sd, len(x))), kid, rng.random(len(x)) * 6.283], 1))
    # dry upper-bank rocks (in-channel / waterline boulders are placed by A1's lib_water)
    steepbank = smoothstep(0.1, 0.5, slope)
    bank = np.exp(-((dwater - 7) / 5) ** 2) * ~wet * (0.3 + 0.7 * steepbank)
    add(bank * np.clip(0.5 + 0.5 * n15, 0, 1) * 0.25, 1.6, {'boulder': 1.0, 'rock_small': 1.5}, -0.1, 0.3)
    # talus below cliffs / rock outcrops, scattered rock on steep ground
    tal = np.exp(-drock / 15) * smoothstep(0.2, 0.55, slope) * ~rock + rock * 0.25
    add(tal * 0.6, 1.5, {'boulder_large': 0.5, 'boulder': 1.0, 'rock_small': 0.8}, 0.1, 0.35)
    # sparse forest-floor boulders (more on ridges / steep)
    add(forest * (0.012 + 0.04 * smoothstep(0.4, 0.9, slope) + 0.02 * np.clip(tpi, 0, 1)), 2.0, {'boulder': 1.0, 'rock_small': 1.5}, -0.1, 0.3)
    # fallen logs / branches / debris on the forest floor (more in moist hollows)
    ff = forest * smoothstep(0, 8, sdn) * (0.05 + 0.08 * moist)
    add(ff, 2.4, {'log': 1.0, 'log_mossy': 0.8, 'branches': 1.6, 'bark_debris': 0.6}, 0.0, 0.2)
    # creek debris: logs, roots along creek banks
    add(np.exp(-dwater / 6) * ~wet * forest * 0.12, 1.6, {'log_mossy': 1.0, 'roots': 1.0, 'branches': 0.6}, 0.0, 0.2)
    # stumps: logging near forest edges, roads, fields
    add(np.exp(-np.abs(sdn) / 15) * 0.03 + forest * np.exp(-np.clip(road1, 0, None) / 25) * 0.02, 2.4, {'stump': 1.0}, 0.0, 0.2)
    if not out:
        return np.zeros((0, 6), np.float32)
    return np.concatenate(out).astype(np.float32)


def run(T, cls):
    veg, props, eco = scatter(T, cls)
    out = path('public/world')
    os.makedirs(out, exist_ok=True)
    veg.astype('<f4').tofile(os.path.join(out, 'vegetation_f32.bin'))
    props.astype('<f4').tofile(os.path.join(out, 'props_f32.bin'))
    eco.tofile(os.path.join(out, 'eco_u8.bin'))
    with open(os.path.join(out, 'eco.json'), 'w') as f:
        json.dump({'w': W, 'h': H, 'channels': ['moisture', 'disturbed', 'canopy', 'field_type', 'field_angle', 'hedge', 'tpi', 'talus', 'road_edge_m/25.5', 'rail_bridge_edge_m/25.5', 'rock_exposure'],
                   'field_types': FIELD_TYPES, 'species': SPECIES, 'props': PROPS,
                   'vegetation': {'file': 'vegetation_f32.bin', 'stride': 6, 'count': int(len(veg))},
                   'props_file': {'file': 'props_f32.bin', 'stride': 6, 'count': int(len(props))}}, f, indent=1)
    s = veg[:, 4].astype(int)
    web = ~np.isin(s, [SID[n] for n in NOT_WEB])
    kind = np.isin(s, [SID[n] for n in CONIFERS]).astype(np.float32)
    trees = np.stack([veg[:, 0], veg[:, 1], veg[:, 2], np.clip(veg[:, 3], 0.5, 1.5), kind], 1)[web]
    from collections import Counter
    cnt = Counter(SPECIES[i] for i in s)
    print(f'vegetation: {len(veg)} plants ({web.sum()} trees for web), {len(props)} props')
    print('  ' + ', '.join(f'{k} {v}' for k, v in sorted(cnt.items(), key=lambda t: -t[1])))
    return trees.astype(np.float32)


