"""Ecosystem vegetation + ground-dressing scatter (Agent 3: vegetation / environment art).

Called from export_web.scatter_trees(T, cls). Instead of one uniform density scatter,
vegetation follows southern-Appalachian ecology derived from the terrain and land use:

  * ecology rasters (2.5 m): slope, aspect (sun exposure), topographic position (ridge /
    hollow), D8 flow accumulation -> moisture, distance to water / roads / rail / forest edge
  * canopy trees: dense mixed forest on slopes; oak-hickory + white / Virginia pine on dry
    ridges and south faces; tulip poplar, red maple and hemlock in moist coves and along
    creeks; thin growth and snags on exposed rock
  * irregular forest edges (noise-displaced) with a shrub / sapling / young-pine
    transition belt; understory dogwood, saplings, rhododendron / laurel thickets in
    hollows and on creek banks, laurel on dry rocky ridges
  * farmland partitioned into fields (pasture / hay / plowed / broomsedge fallow) with
    hedgerows + fence-line trees, lone open-grown field oaks, yard trees in towns
  * brush and weeds along road and rail corridors, disturbed ground near infrastructure
  * clear zones: nothing on pavement, shoulders, rail ballast or water (road widths from
    road_types + a per-type maintained clear zone)

Outputs (public/world/, gitignored, regenerated by export_web):
  vegetation_f32.bin  float32 [x_px, y_px, z_m, scale, species_id, seed]  (lib_trees.SPECIES order)
  props_f32.bin       float32 [x_px, y_px, z_m, scale, kind, rot]         (lib_props.KINDS order)
  eco_u8.bin          uint8 H x W x 10: moisture, disturbed, canopy, field_type, field_angle,
                      hedge, tpi(128=0), talus, road edge dist, rail/bridge edge dist   (terrain material / ground cover drivers)
  eco.json            channel descriptor
Returns the web-compatible trees array [x, y, z, scale, kind(0 hardwood / 1 conifer)].
"""
